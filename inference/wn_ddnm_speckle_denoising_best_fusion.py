"""
WN-DDNM: Wavelet-based Null-space Denoising Diffusion Model

Key Innovation:
- Wavelet-based Low-Pass Filter (LPF) as degradation operator A
- Range-Null space decomposition for speckle removal:
  - Range-space: A†·A·y_obs (preserved low-frequency tissue structure)
  - Null-space: (I - A†A)·x̂_0|t (high-frequency regenerated by diffusion prior)

Algorithm (Linear Space):
1. y_obs = normalize(input)  # Work in [0, 1] linear space
2. Pre-compute range-space: A†·A·y_obs (low-frequency tissue)
3. For each timestep t in reverse diffusion:
   - Predict x̂_0|t from model
   - Null-space: (I - A†A)·x̂_0|t (high-frequency from diffusion)
   - Combine: x̄_0|t = Range(observation) + Null(prediction)
   - DDIM step: x_{t-1} = update(x̄_0|t)

Advantages:
- Clear separation: Range-space (tissue) / Null-space (speckle)
- Diffusion prior generates natural high-frequency instead of noise
- Works in linear space matching diffusion model training
- No log/exp transform instability issues
"""
