    def _setup_diffusion_schedule(self):
        """Setup beta/alpha schedules"""
        betas = get_beta_schedule(
            self.config['noise_schedule'],
            0.0001,
            0.02,
            self.num_timesteps
        )
        self.betas = torch.from_numpy(betas).float().to(self.device)

        alphas = 1.0 - self.betas
        self.alphas_cumprod = torch.cumprod(alphas, dim=0)
        self.alphas_cumprod_prev = torch.cat([
            torch.ones(1).to(self.device),
            self.alphas_cumprod[:-1]
        ])

        self.sqrt_alphas_cumprod = torch.sqrt(self.alphas_cumprod)
        self.sqrt_one_minus_alphas_cumprod = torch.sqrt(1.0 - self.alphas_cumprod)
        self.sqrt_recip_alphas_cumprod = torch.sqrt(1.0 / self.alphas_cumprod)
        self.sqrt_recipm1_alphas_cumprod = torch.sqrt(1.0 / self.alphas_cumprod - 1)

    def _setup_timesteps(self):
        """Setup subsampled timesteps with various scheduling options

        Supported schedules:
        - 'uniform': Standard uniform spacing (default)
        - 'karras': Karras et al. schedule (better quality at low steps)
        - 'exponential': Exponential spacing (large steps early, small late)
        - 'quadratic': Quadratic spacing

        Note: All schedules use DDIM-style updates with WN-DDNM range-null decomposition.
        """
        n = self.ddim_steps
        T = self.num_timesteps

        if self.timestep_schedule == 'uniform':
            # Standard uniform spacing
            step = T // n
            self.ddim_timesteps = list(range(0, T, step))[::-1]

        elif self.timestep_schedule == 'karras':
            # Karras et al. schedule: σ_i = (σ_max^(1/ρ) + i/(n-1) * (σ_min^(1/ρ) - σ_max^(1/ρ)))^ρ
            # Convert sigma to timesteps via alpha_bar relationship
            rho = 7.0
            sigma_min = 0.002
            sigma_max = 80.0

            ramp = np.linspace(0, 1, n)
            min_inv_rho = sigma_min ** (1 / rho)
            max_inv_rho = sigma_max ** (1 / rho)
            sigmas = (max_inv_rho + ramp * (min_inv_rho - max_inv_rho)) ** rho

            # Convert sigmas to timesteps: sigma = sqrt((1-alpha_bar)/alpha_bar)
            # So alpha_bar = 1 / (1 + sigma^2)
            alpha_bars = 1.0 / (1.0 + sigmas ** 2)

            # Find closest timesteps
            alphas_np = self.alphas_cumprod.cpu().numpy()
            timesteps = []
            for ab in alpha_bars:
                t = np.argmin(np.abs(alphas_np - ab))
                timesteps.append(int(t))

            # Remove duplicates while preserving order, then reverse for T -> 0
            seen = set()
            unique_timesteps = []
            for t in timesteps:
                if t not in seen:
                    seen.add(t)
                    unique_timesteps.append(t)
            self.ddim_timesteps = unique_timesteps

        elif self.timestep_schedule == 'exponential':
            # Exponential spacing: more steps near t=0 (fine details)
            # t_i = T * exp(-k * i/n), where k controls steepness
            k = 3.0  # Steepness factor
            ramp = np.linspace(0, 1, n)
            timesteps = T * np.exp(-k * ramp)
            timesteps = np.clip(timesteps, 0, T - 1).astype(int)

            # Remove duplicates and reverse
            seen = set()
            unique_timesteps = []
            for t in timesteps:
                if t not in seen:
                    seen.add(t)
                    unique_timesteps.append(int(t))
            self.ddim_timesteps = unique_timesteps

        elif self.timestep_schedule == 'quadratic':
            # Quadratic spacing: t_i = T * (1 - (i/n)^2)
            ramp = np.linspace(0, 1, n)
            timesteps = T * (1 - ramp ** 2)
            timesteps = np.clip(timesteps, 0, T - 1).astype(int)

            # Remove duplicates
            seen = set()
            unique_timesteps = []
            for t in timesteps:
                if t not in seen:
                    seen.add(t)
                    unique_timesteps.append(int(t))
            self.ddim_timesteps = unique_timesteps

        else:
            raise ValueError(f"Unknown timestep_schedule: {self.timestep_schedule}")

        # Ensure we end at t=0 or close to it
        if self.ddim_timesteps[-1] > 0:
            self.ddim_timesteps.append(0)

