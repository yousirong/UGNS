class LowPassFilterOperator:
    """
    Low-Pass Filter as DDNM degradation operator A

    For WN-DDNM, we define:
    - A: Low-pass filter (extracts low-frequency)
    - A†: Adjoint/pseudo-inverse (same as A for symmetric LPF)
    - Range-space: A†·A (low-frequency subspace)
    - Null-space: I - A†·A (high-frequency subspace)

    Supports two modes:
    1. 'avgpool': AvgPool2d + Upsample (spatial domain)
    2. 'wavelet': DWT LL sub-band extraction (wavelet domain)

    Wavelet mode is preferred for ultrasound as it provides:
    - Multi-scale decomposition
    - Natural tissue-speckle separation
    """

    def __init__(
        self,
        mode='wavelet',
        kernel_size=4,
        wavelet='sym4',
        level=3,
        srad_iterations=15,
        srad_q0=0.4,
        srad_delta_t=0.25,
    ):
        """
        Args:
            mode: 'wavelet' or 'avgpool'
            kernel_size: Kernel size for avgpool mode
            wavelet: Wavelet family for wavelet mode
            level: Decomposition level for wavelet mode
        """
        self.mode = mode
        self.kernel_size = kernel_size
        self.wavelet = wavelet
        self.level = level
        self.srad_iterations = srad_iterations
        self.srad_q0 = srad_q0
        self.srad_delta_t = srad_delta_t

        print(f"\n{'='*60}")
        print(f"LowPassFilterOperator Initialized")
        print(f"{'='*60}")
        print(f"Mode: {mode}")
        if mode == 'avgpool':
            print(f"Kernel size: {kernel_size}")
        else:
            print(f"Wavelet: {wavelet}, Level: {level}")
        print(f"{'='*60}\n")

    def forward(self, x):
        """
        A: Apply low-pass filter

        Args:
            x: Input image (2D numpy array)
        Returns:
            Low-pass filtered image (same size as input)
        """
        if self.mode == 'avgpool':
            return self._avgpool_forward(x)
        else:
            return self._wavelet_forward(x)

    def _avgpool_forward(self, x):
        """AvgPool + Upsample implementation"""
        k = self.kernel_size
        H, W = x.shape

        # Pad to make divisible by kernel size
        pad_h = (k - H % k) % k
        pad_w = (k - W % k) % k
        if pad_h > 0 or pad_w > 0:
            x_padded = np.pad(x, ((0, pad_h), (0, pad_w)), mode='reflect')
        else:
            x_padded = x

        # Convert to tensor for pooling
        x_tensor = torch.from_numpy(x_padded).float().unsqueeze(0).unsqueeze(0)

        # AvgPool
        pooled = F.avg_pool2d(x_tensor, k, k)

        # Upsample back to original size
        upsampled = F.interpolate(pooled, size=x_padded.shape, mode='bilinear', align_corners=False)

        # Crop to original size
        result = upsampled.squeeze().numpy()[:H, :W]

        return result

    def _wavelet_forward(self, x):
        """
        Wavelet LL sub-band extraction

        This extracts only the low-frequency (LL) component and reconstructs,
        effectively zeroing out all high-frequency detail coefficients.
        """
        # Multi-level decomposition
        coeffs = pywt.wavedec2(x, self.wavelet, level=self.level, mode='symmetric')

        # Keep only approximation, zero out all details
        coeffs_lpf = [coeffs[0]]  # LL approximation
        for i in range(1, len(coeffs)):
            cH, cV, cD = coeffs[i]
            coeffs_lpf.append((np.zeros_like(cH), np.zeros_like(cV), np.zeros_like(cD)))

        # Reconstruct
        result = pywt.waverec2(coeffs_lpf, self.wavelet, mode='symmetric')

        # Handle size mismatch due to wavelet padding
        result = result[:x.shape[0], :x.shape[1]]

        return result

    def srad_filter(self, x, num_iter=None, q0=None, delta_t=None):
        """Speckle-Reducing Anisotropic Diffusion (SRAD) filter."""
        iterations = self.srad_iterations if num_iter is None else num_iter
        q0_val = self.srad_q0 if q0 is None else q0
        dt = self.srad_delta_t if delta_t is None else delta_t
        dt = np.clip(dt, 1e-4, 0.25)

        img = x.astype(np.float32)
        eps = 1e-12

        for _ in range(max(1, iterations)):
            padded = np.pad(img, 1, mode='edge')
            c = padded[1:-1, 1:-1]
            n = padded[:-2, 1:-1]
            s = padded[2:, 1:-1]
            e = padded[1:-1, 2:]
            w = padded[1:-1, :-2]

            dN = n - c
            dS = s - c
            dE = e - c
            dW = w - c

            c_sq = c * c + eps
            grad_sq = (dN ** 2 + dS ** 2 + dE ** 2 + dW ** 2) / c_sq
            laplace = (dN + dS + dE + dW) / (c + eps)

            denom = (1.0 + 0.25 * laplace)
            q_sq = (0.5 * grad_sq - 0.25 * laplace ** 2) / (denom * denom + eps)

            if q0_val is None or q0_val <= 0:
                q0_sq = float(np.mean(q_sq))
            else:
                q0_sq = float(q0_val * q0_val)

            q0_sq = max(q0_sq, eps)
            c_coef = 1.0 / (1.0 + (q_sq - q0_sq) / (q0_sq * (1.0 + q0_sq) + eps))
            c_coef = np.clip(c_coef, 0.0, 1.0)

            img = c + (dt / 4.0) * (c_coef * dN + c_coef * dS + c_coef * dE + c_coef * dW)

        return np.clip(img, 0.0, 1.0)

    def adjoint(self, y):
        """
        A†: Adjoint operator

        For symmetric LPF, the adjoint is the same as forward.
        This is because LPF is a projection operator.
        """
        return self.forward(y)

    def range_space_projection(self, x):
        """
        A†·A·x: Project onto range-space (observed low-frequency)

        Implemented explicitly as A†(A(x)) to match the DDNM formulation.
        For symmetric LPF, A† = A and A is idempotent, so A†A ≈ A.

        """
        # Explicit A†A structure (even if A is symmetric)
        return self.adjoint(self.forward(x))

    def null_space_projection(self, x):
        """
        (I - A†A)·x: Project onto null-space (unobserved high-frequency)

        This extracts the high-frequency components that are
        NOT captured by the low-pass filter.

        """
        return x - self.range_space_projection(x)

    def forward_torch(self, x):
        """Torch version of forward for batch processing"""
        if self.mode == 'avgpool':
            k = self.kernel_size
            # x: (B, 1, H, W)
            pooled = F.avg_pool2d(x, k, k)
            upsampled = F.interpolate(pooled, size=x.shape[-2:], mode='bilinear', align_corners=False)
            return upsampled
        else:
            # Wavelet mode - process each sample in batch
            B, C, H, W = x.shape
            results = []
            for b in range(B):
                x_np = x[b, 0].cpu().numpy()
                result = self._wavelet_forward(x_np)
                results.append(result)
            return torch.from_numpy(np.stack(results)).unsqueeze(1).float().to(x.device)





