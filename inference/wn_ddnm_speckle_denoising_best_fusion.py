def configure_cuda_runtime(device, batch_size):
    """Warn about small GPUs and arrange end-of-run peak-memory reporting."""
    requested = torch.device(device)
    if requested.type != 'cuda' or not torch.cuda.is_available():
        return

    device_index = requested.index
    if device_index is None:
        device_index = torch.cuda.current_device()
    properties = torch.cuda.get_device_properties(device_index)
    if properties.total_memory < 10 * 1024 ** 3:
        warnings.warn(
            "The selected GPU has less than 10 GiB of VRAM. Try --batch_size 5 "
            "or --batch_size 2 if allocation fails; changing batch_size changes "
            "the sampled ensemble because UGNS seeds each chunk separately.",
            RuntimeWarning,
        )

    torch.cuda.reset_peak_memory_stats(device_index)

    def _report_peak_memory():
        peak_gib = torch.cuda.max_memory_allocated(device_index) / (1024 ** 3)
        print(f"Peak CUDA memory allocated: {peak_gib:.3f} GiB")

    atexit.register(_report_peak_memory)


